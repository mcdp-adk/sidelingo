export type UiLanguage = "zh-Hans" | "en";

/** Any Chinese gives Simplified Chinese, anything else English. */
function uiLanguageOf(tag: string): UiLanguage {
  return /^zh(-|$)/i.test(tag) ? "zh-Hans" : "en";
}

